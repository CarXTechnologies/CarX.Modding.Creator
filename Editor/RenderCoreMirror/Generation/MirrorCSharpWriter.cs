using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Plugins.CarX.Modding.Creator.RenderCoreMirror
{
	/// <summary>
	/// Пишет Runtime/RenderCore/ModRenderCoreVariants.g.cs: только данные (CreateVariants, CreateSuggestions, LockContentHash) вызовами
	/// помощников Texture/Packed/Value из ручного partial ModRenderCoreVariants.cs. Табы, LF, числа InvariantCulture, именованные аргументы
	/// для литералов; ни времени, ни коммитов — одинаковый вход даёт байт-в-байт одинаковый файл.
	/// </summary>
	public static class MirrorCSharpWriter
	{
		public const string RegenerateMenu = "ModSystem/Render Core/Regenerate Table";
		public const string RegenerateCommand = "dotnet run --project Tools~/RenderCoreMirror -- generate --sdk .";

		private const string VariantIndent = "\t\t\t\t";
		private const string BodyIndent = "\t\t\t\t\t";
		private const string PropertyIndent = "\t\t\t\t\t\t";
		private const string ContinuationIndent = "\t\t\t\t\t\t\t";

		public static string Write(MirrorGenerationResult result)
		{
			if (!result.Succeeded)
			{
				throw new InvalidOperationException("генерация заблокирована находками Breaking/Error: таблица не пишется");
			}

			var builder = new StringBuilder();
			Line(builder, "// <auto-generated>");
			Line(builder, "// Сгенерировано зеркалом rendercore из Editor/RenderCoreMirror/RenderCoreLock.txt и RenderCoreMirrorAnnotations, не редактировать.");
			Line(builder, $"// Перегенерировать: {RegenerateMenu} или (из папки CarX.Modding.Creator) {RegenerateCommand}");
			Line(builder, "// Не предлагаются (нет аннотации): " + (result.notAnnotated.Count == 0 ? "—" : string.Join(", ", result.notAnnotated)));
			Line(builder, "// </auto-generated>");
			Line(builder, "using System;");
			Line(builder, "using UnityEngine;");
			Line(builder, "");
			Line(builder, "namespace Plugins.CarX.Modding.Creator.Runtime");
			Line(builder, "{");
			Line(builder, "\tpublic static partial class ModRenderCoreVariants");
			Line(builder, "\t{");
			Line(builder, $"\t\tpublic const string LockContentHash = {Literal(result.lockContentHash)};");
			Line(builder, "");
			Line(builder, "\t\tprivate static ModRenderCoreVariant[] CreateVariants()");
			Line(builder, "\t\t{");
			WriteArray(builder, result.variants, WriteVariant, "ModRenderCoreVariant");
			Line(builder, "\t\t}");
			Line(builder, "");
			Line(builder, "\t\tprivate static ModRenderCoreSuggestion[] CreateSuggestions()");
			Line(builder, "\t\t{");
			WriteArray(builder, result.suggestions, WriteSuggestion, "ModRenderCoreSuggestion");
			Line(builder, "\t\t}");
			Line(builder, "\t}");
			Line(builder, "}");
			return builder.ToString();
		}

		/// <summary>Строковый литерал C# (UTF-8 как есть, управляющие и переводы строк — escape).</summary>
		public static string Literal(string value)
		{
			if (value == null)
			{
				return "null";
			}

			var builder = new StringBuilder(value.Length + 2);
			builder.Append('"');

			foreach (char character in value)
			{
				switch (character)
				{
					case '"':
						builder.Append("\\\"");
						break;
					case '\\':
						builder.Append("\\\\");
						break;
					case '\n':
						builder.Append("\\n");
						break;
					case '\r':
						builder.Append("\\r");
						break;
					case '\t':
						builder.Append("\\t");
						break;
					default:
						// Переводы строк Unicode и прочие управляющие в литерале C# недопустимы.
						if (char.IsControl(character) || character == '\u0085' || character == '\u2028' || character == '\u2029')
						{
							builder.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
						}
						else
						{
							builder.Append(character);
						}

						break;
				}
			}

			return builder.Append('"').ToString();
		}

		private static void WriteArray<T>(StringBuilder builder, IReadOnlyList<T> items, Action<StringBuilder, T, bool> write, string elementType)
		{
			if (items.Count == 0)
			{
				Line(builder, $"\t\t\treturn Array.Empty<{elementType}>();");
				return;
			}

			Line(builder, "\t\t\treturn new[]");
			Line(builder, "\t\t\t{");

			for (int index = 0; index < items.Count; index++)
			{
				write(builder, items[index], index == items.Count - 1);
			}

			Line(builder, "\t\t\t};");
		}

		private static void WriteVariant(StringBuilder builder, MirrorVariant variant, bool last)
		{
			string keywords = variant.keywords.Count == 0
				? "Array.Empty<string>()"
				: "new[] { " + string.Join(", ", variant.keywords.Select(Literal)) + " }";

			Line(builder, $"{VariantIndent}new ModRenderCoreVariant({Literal(variant.name)}, id: {Int(variant.id)}, queue: {Int(variant.queue)}, " +
				$"ModRenderCoreRenderType.{variant.renderType}, {keywords},");
			Line(builder, $"{BodyIndent}ModRenderCoreVertexColors.{variant.vertexColors}, {Streams(variant.requiredStreams)},");

			string head = $"{BodyIndent}unavailableReason: {Literal(variant.unavailableReason)}, revision: {Int(variant.revision)}, ";

			if (variant.properties.Count == 0)
			{
				Line(builder, head + "Array.Empty<ModRenderCoreVariantProperty>())" + (last ? "" : ","));
				return;
			}

			Line(builder, head + "new[]");
			Line(builder, BodyIndent + "{");

			for (int index = 0; index < variant.properties.Count; index++)
			{
				WriteProperty(builder, variant.properties[index], index == variant.properties.Count - 1);
			}

			Line(builder, BodyIndent + "})" + (last ? "" : ","));
		}

		private static void WriteProperty(StringBuilder builder, MirrorProperty property, bool last)
		{
			string end = last ? "" : ",";
			string common = $"{Literal(property.name)}, {Literal(property.label)}, {Literal(property.tooltip)}";

			if (property.type == MirrorPropertyType.Texture && property.source == MirrorSource.Surface)
			{
				string channels = string.Join(", ", property.channels.Select(channel => "ModRenderCoreChannel." + channel));
				Line(builder, $"{PropertyIndent}Packed({common}, layer: {Int(property.layer)}, {channels}){end}");
				return;
			}

			if (property.type == MirrorPropertyType.Texture)
			{
				Line(builder, $"{PropertyIndent}Texture({common}, ModRenderCoreSource.{property.source}, layer: {Int(property.layer)}){end}");
				return;
			}

			string labels = property.vectorLabels == null
				? "vectorLabels: null"
				: "new[] { " + string.Join(", ", property.vectorLabels.Select(Literal)) + " }";
			Line(builder, $"{PropertyIndent}Value({common}, ModRenderCorePropertyType.{property.type}, ModRenderCoreSource.{property.source},");
			Line(builder, $"{ContinuationIndent}{Vector(property.defaultValue)}, {labels}){end}");
		}

		private static void WriteSuggestion(StringBuilder builder, MirrorSuggestion suggestion, bool last)
		{
			Line(builder, $"{VariantIndent}new ModRenderCoreSuggestion(ModRenderCoreRenderType.{suggestion.renderType}, hasNormal: {Bool(suggestion.hasNormal)}, " +
				$"hasEmission: {Bool(suggestion.hasEmission)}, {Literal(suggestion.variant)}){(last ? "" : ",")}");
		}

		/// <summary>Флаги в порядке значений: "ModRenderCoreVertexStreams.Position | ModRenderCoreVertexStreams.Normal".</summary>
		private static string Streams(MirrorVertexStreams streams)
		{
			if (streams == MirrorVertexStreams.None)
			{
				return "ModRenderCoreVertexStreams.None";
			}

			var parts = new List<string>();

			foreach (MirrorVertexStreams flag in Enum.GetValues(typeof(MirrorVertexStreams)).Cast<MirrorVertexStreams>().OrderBy(flag => (int)flag))
			{
				if (flag != MirrorVertexStreams.None && (streams & flag) == flag)
				{
					parts.Add("ModRenderCoreVertexStreams." + flag);
				}
			}

			return string.Join(" | ", parts);
		}

		private static string Vector(MirrorVector value)
		{
			return $"new Vector4({MirrorVector.FormatComponent(value.x)}, {MirrorVector.FormatComponent(value.y)}, {MirrorVector.FormatComponent(value.z)}, " +
				$"{MirrorVector.FormatComponent(value.w)})";
		}

		private static string Int(int value)
		{
			return value.ToString(CultureInfo.InvariantCulture);
		}

		private static string Bool(bool value)
		{
			return value ? "true" : "false";
		}

		private static void Line(StringBuilder builder, string text)
		{
			builder.Append(text).Append('\n');
		}
	}
}
